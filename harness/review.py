"""Build eval/verdict_review.md: every verdict of the given runs, for review.

    python harness/review.py out-final-pelican out-final-monkey ...

For each round: the reference and the attempt side by side, the judge's scores
and defects (and the A/B-swapped confirmation when there is one), what the
firewall passed on to the refiner, and an empty "My review" block to fill in.
PNGs are copied to eval/review/<run>/ so the page renders on GitHub
(run folders are not committed).
"""
import json
import shutil
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
EVAL = REPO / "eval"
CRITERIA = ("fidelity", "coherence", "readability", "composition", "craft")


def load(path):
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def defects_md(defects):
    if not defects:
        return "_none_\n"
    return "".join(f"- **{d['severity']}** ({d['criterion']}): {d['what']} _Where:_ {d['where']}. "
                   f"_Expected:_ {d['expected']}\n" for d in defects)


def scores_md(v, conf):
    head = "| | " + " | ".join(CRITERIA) + " | total |\n|---|" + "---|" * (len(CRITERIA) + 1) + "\n"
    rows = ""
    for label, verdict in (("judgment", v), ("confirmation (A/B swapped)", conf)):
        if verdict is None:
            continue
        for role in ("reference", "attempt"):
            s = verdict[role]["scores"]
            rows += (f"| {role}, {label} | " + " | ".join(str(s[c]) for c in CRITERIA)
                     + f" | **{sum(s.values())}** |\n")
    return head + rows


def run_md(run):
    run = Path(run)
    summary = load(run / "summary.json")
    if summary is None:
        return f"## {run.name}\n\n_no summary.json_\n\n"
    dest = EVAL / "review" / run.name
    dest.mkdir(parents=True, exist_ok=True)
    rel = dest.relative_to(EVAL).as_posix()
    shutil.copyfile(run / "rounds" / "00" / "reference.png", dest / "reference.png")

    out = [f"## {run.name}\n\n",
           f"Prompt: _{summary['prompt']}_  \n",
           f"Stop: **{summary['stop_reason']}** after round {summary['rounds']}, "
           f"final = round {summary['final_round']}, total ${summary['total_cost_usd']:.4f}\n\n"]
    for rd in sorted((run / "rounds").iterdir()):
        v = load(rd / "verdict.json")
        if v is None:
            continue
        conf = load(rd / "verdict_confirm.json")
        fb = load(rd / "feedback.json")
        png = f"attempt-{rd.name}.png"
        shutil.copyfile(rd / "attempt.png", dest / png)
        out.append(f"### {run.name} · round {rd.name}\n\n")
        out.append("| reference | attempt |\n|---|---|\n"
                   f"| <img src=\"{rel}/reference.png\" width=\"360\"> "
                   f"| <img src=\"{rel}/{png}\" width=\"360\"> |\n\n")
        if fb is not None:
            out.append(f"<details><summary>Feedback the refiner received for this round "
                       f"(from round {fb['source_round']:02d}): {len(fb['kept'])} defect(s) passed, "
                       f"{len(fb['dropped'])} dropped</summary>\n\n{defects_md(fb['kept'])}\n</details>\n\n")
        out.append(scores_md(v, conf) + "\n")
        verdict_line = f"Judge: parity **{'yes' if v['parity'] else 'no'}**"
        if conf is not None:
            verdict_line += f"; confirmation: parity **{'yes' if conf['parity'] else 'no'}**"
        out.append(verdict_line + f". _{v['parity_reason']}_\n\n")
        out.append(f"**Attempt defects (judge):**\n\n{defects_md(v['attempt']['defects'])}\n")
        out.append(f"**Reference defects (judge, never shown to the refiner):**\n\n"
                   f"{defects_md(v['reference']['defects'])}\n")
        out.append("**My review:**\n\n"
                   "- Judge right on parity? yes / no\n"
                   "- Missed defects:\n"
                   "- Wrong or unfair defects/scores:\n"
                   "- Notes:\n\n---\n\n")
    return "".join(out)


def main(argv):
    force = "--force" in argv
    argv = [a for a in argv if a != "--force"]
    if not argv:
        print(__doc__)
        return 1
    path = EVAL / "verdict_review.md"
    if path.exists() and not force:
        # The page holds review notes: never overwrite them silently.
        print(f"{path.relative_to(REPO).as_posix()} already exists (it may hold your notes); "
              f"use --force to overwrite it", file=sys.stderr)
        return 1
    EVAL.mkdir(exist_ok=True)
    body = "".join(run_md(r) for r in argv)
    page = ("# Verdict review\n\n"
            "Every verdict of the runs below, reviewed: where was the judge wrong?\n"
            "Generated by `harness/review.py`; the \"My review\" blocks are filled in.\n\n"
            + body)
    path.write_text(page, encoding="utf-8")
    print(f"-> {path.relative_to(REPO).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
